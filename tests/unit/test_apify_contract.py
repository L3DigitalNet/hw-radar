from hw_radar.catalog.models import RunCompleteness, StockStatus
from hw_radar.catalog.models.ops import TruncationReason

REPO_ROOT: Final = Path(__file__).resolve().parents[2]
ACTOR_DIR: Final = REPO_ROOT / "actors" / "hw-radar-synthetic-collector"
CONTRACT_DIR: Final = ACTOR_DIR / "contract"
FIXTURE_DIR: Final = REPO_ROOT / "tests" / "fixtures" / "apify_contract" / "v1"

C = RunCompleteness
T = TruncationReason

# The MS2-D-14 mapping table: fixture -> (completeness, reason prefix, truncation reason).
EXPECTED: Final[dict[str, tuple[RunCompleteness, str, TruncationReason | None]]] = {
    "complete": (C.COMPLETE, "complete", None),
    "complete-empty": (C.COMPLETE, "complete_empty", None),
    "ambiguous-empty": (C.FAILED, "ambiguous_empty", None),
    "nonempty-unusable": (C.FAILED, "no_usable_items", None),
    "truncated-by-pages": (C.TRUNCATED, "truncated: pages", T.PAGE_LIMIT),
    "truncated-by-items": (C.TRUNCATED, "truncated: items", T.ITEM_LIMIT),
    "truncated-by-bytes": (C.TRUNCATED, "truncated: bytes", T.RESOURCE_LIMIT),
    "truncated-by-time": (C.TRUNCATED, "truncated: time", T.TIME_LIMIT),
    "timed-out": (C.TRUNCATED, "truncated: time", T.TIME_LIMIT),
    "partial-with-errors": (C.PARTIAL_FAILURE, "errors_reported: injected_fetch_error", None),
    "failed-with-items": (C.PARTIAL_FAILURE, "remote_failed_with_items: FAILED", None),
    "missing-output": (C.FAILED, "missing_output", None),
    "unknown-schema": (C.FAILED, "unknown_schema_version", None),
    "count-mismatch": (C.FAILED, "contradictory_report: count_mismatch", None),
    "complete-with-limit-hit": (C.FAILED, "contradictory_report: complete_with_limit_hit", None),
    "status-mismatch": (C.FAILED, "contradictory_report: status_mismatch", None),
    "scope-mismatch": (C.FAILED, "scope_mismatch", None),
}


def _fixture(name: str) -> dict[str, Any]:
    return json.loads((FIXTURE_DIR / f"{name}.json").read_text(encoding="utf-8"))


def _admitted(fixture: dict[str, Any]) -> AdmittedRun:
    admitted = fixture["admitted"]
    return AdmittedRun(
        query_scope=QueryScope.model_validate(admitted["queryScope"]),
        actor_name=admitted["actorName"],
    )


def _classify(
    fixture: dict[str, Any], *, remote_status: str | None = None, output: object = ...
) -> RunClassification:
    rows: list[object] = list(fixture["datasetItems"])
    return classify_run(
        remote_status or fixture["remoteStatus"],
        fixture["output"] if output is ... else output,
        len(rows),
        len(usable_rows(rows)),
        admitted=_admitted(fixture),
    )


def _with_report(name: str, **changes: object) -> dict[str, Any]:
    """A copy of a fixture's OUTPUT with completeness keys replaced (None deletes)."""
    output = copy.deepcopy(_fixture(name)["output"])
    for key, value in changes.items():
        if value is None:
            output["completeness"].pop(key, None)
        else:
            output["completeness"][key] = value
    return output


