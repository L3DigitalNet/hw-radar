# ── Truncation reasons (revision 5) ───────────────────────────────────────────


def test_truncation_reason_distinguishes_items_pages_time_bytes() -> None:
    reasons = {
        name: _classify(_fixture(name)).truncation_reason
        for name in (
            "truncated-by-items",
            "truncated-by-pages",
            "truncated-by-time",
            "truncated-by-bytes",
        )
    }

    assert reasons == {
        "truncated-by-items": T.ITEM_LIMIT,
        "truncated-by-pages": T.PAGE_LIMIT,
        "truncated-by-time": T.TIME_LIMIT,
        "truncated-by-bytes": T.RESOURCE_LIMIT,
    }
    assert all(_classify(_fixture(name)).completeness is C.TRUNCATED for name in reasons)


def _limits(**hit: bool) -> dict[str, bool]:
    return {name: hit.get(name, False) for name in ("pages", "requests", "items", "time", "bytes")}


@pytest.mark.parametrize(
    ("hit", "expected", "listed"),
    [
        (
            _limits(pages=True, requests=True, items=True, time=True, bytes=True),
            T.TIME_LIMIT,
            "time, bytes, requests, pages, items",
        ),
        (_limits(bytes=True, requests=True), T.RESOURCE_LIMIT, "bytes, requests"),
        (_limits(requests=True, pages=True), T.REQUEST_LIMIT, "requests, pages"),
        (_limits(pages=True, items=True), T.PAGE_LIMIT, "pages, items"),
    ],
)
def test_truncation_precedence_is_time_bytes_requests_pages_items(
    hit: dict[str, bool], expected: TruncationReason, listed: str
) -> None:
    output = _with_report("truncated-by-items", limitsHit=hit)

    result = _classify(_fixture("truncated-by-items"), output=output)

    assert result == RunClassification(C.TRUNCATED, f"truncated: {listed}", expected)


def test_timed_out_without_an_actor_flag_is_a_time_limit() -> None:
    output = _with_report("truncated-by-pages", limitsHit=_limits(), truncated=True)

    result = _classify(_fixture("truncated-by-pages"), remote_status="TIMED-OUT", output=output)

    assert result == RunClassification(C.TRUNCATED, "truncated: time", T.TIME_LIMIT)


def test_timed_out_run_that_claimed_completion_is_still_truncated() -> None:
    result = _classify(_fixture("complete"), remote_status="TIMED-OUT")

    assert result == RunClassification(C.TRUNCATED, "truncated: time", T.TIME_LIMIT)


