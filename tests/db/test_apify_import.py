def test_row_over_the_byte_cap_is_rejected_before_validation() -> None:
    # An otherwise valid row padded past the serialized-row bound: the size
    # check must win, so an oversized row is never even handed to the validator.
    padded = _row(title="T" * 400)
    assert isinstance(_judge(padded), ParsedListing)
    size = len(json.dumps(padded, ensure_ascii=True, separators=(",", ":")))
    capped = import_row(padded, site_key=SITE, scope_key=SCOPE, max_item_bytes=size - 1)
    assert capped is RowRejection.OVER_BYTE_CAP
    assert _judge(_row(padding="p" * MAX_LISTING_ROW_BYTES)) is RowRejection.OVER_BYTE_CAP


