def _run[T](coro: Coroutine[Any, Any, T]) -> T:
    return asyncio.run(coro)


class FakeApify:
    """MockTransport handler serving one fixture's dataset and OUTPUT record."""

    def __init__(self, rows: list[object], output: object) -> None:
        self.rows = rows
        self.output = output
        self.dataset_requests: list[tuple[int, int]] = []

    def __call__(self, request: httpx.Request) -> httpx.Response:
        if request.url.path == f"/v2/datasets/{DATASET}/items":
            offset = int(request.url.params["offset"])
            limit = int(request.url.params["limit"])
            self.dataset_requests.append((offset, limit))
            return httpx.Response(
                200,
                json=self.rows[offset : offset + limit],
                headers={"X-Apify-Pagination-Total": str(len(self.rows))},
            )
        if request.url.path == f"/v2/key-value-stores/{KV_STORE}/records/{OUTPUT_RECORD_KEY}":
            if self.output is None:
                return httpx.Response(
                    404, json={"error": {"type": "record-not-found", "message": "nope"}}
                )
            if isinstance(self.output, bytes):
                return httpx.Response(200, content=self.output)
            return httpx.Response(200, json=self.output)
        return httpx.Response(500, json={"error": {"type": "unexpected", "message": "path"}})


