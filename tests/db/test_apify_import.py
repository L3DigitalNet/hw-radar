class _LocalAdapter:
    """Local SourceAdapter on the synthetic site whose items carry a fixed body size."""

    name = "synthetic-local"
    site_key = SITE
    run_kind = RunKind.FULL
    expects_json = True
    last_parse_skipped = 0

    def __init__(self, keys: list[str], *, body_bytes: int) -> None:
        self._keys = keys
        self._body = "x" * body_bytes

    async def fetch(self) -> RawBatch:
        # Fresh timestamp per call: observed_at is half of OfferSnapshot's PK.
        return RawBatch(
            source=self.name,
            fetched_at=datetime.now(UTC),
            items=[RawItem(url="https://synthetic.invalid/page", payload_text=self._body)],
        )

    def parse(self, batch: RawBatch) -> list[ParsedListing]:
        return [
            ParsedListing(
                source_listing_key=key,
                url=f"https://synthetic.invalid/{key}",
                title="Synthetic 8TB",
                price=Decimal(100),
                raw_url="https://synthetic.invalid/page",
            )
            for key in self._keys
        ]


def _seed_full_runs(
    site: SourceSite, *, body_bytes: int, provider_kind: str | None, count: int
) -> None:
    """Successful FULL runs whose per-item body average is body_bytes."""
    base = timezone.now()
    for index in range(count):
        detail: dict[str, object] = {"body_bytes": body_bytes}
        if provider_kind is not None:
            detail["provider"] = {"provider_kind": provider_kind}
        ScraperRun.objects.create(
            source_site=site,
            run_kind=RunKind.FULL,
            status=RunStatus.SUCCESS,
            started_at=base + timedelta(seconds=index),
            records_fetched=1,
            detail_json=detail,
        )


def test_provider_switch_does_not_soft_block_imports_or_local_runs(
    synthetic_site: SourceSite,
) -> None:
    # 1. Local history gives the site a 50 kB per-item median. A dataset row is
    #    small JSON with no body text at all, so the EC-007 20% rule would call
    #    every imported row ANTI_BOT if the import ran _classify_batch. One seed
    #    run predates provider evidence (no "provider" key) and must still count.
    _seed_full_runs(synthetic_site, body_bytes=50_000, provider_kind="local", count=3)
    _seed_full_runs(synthetic_site, body_bytes=50_000, provider_kind=None, count=1)
    fixture = _fixture("complete")
    provider = _provider(_provider_run(synthetic_site, fixture), _fake(fixture))

    run, status = _import(provider)

    assert status is RunStatus.SUCCESS, run.error
    assert run.failure_class in ("", None)

    # 2. After the switch, a window's worth of newer remote runs with a huge
    #    per-item average would dominate the median if they were counted, and
    #    push the next ordinary 50 kB local page under 20% of it.
    _seed_full_runs(
        synthetic_site, body_bytes=10_000_000, provider_kind="apify", count=MEDIAN_BODY_WINDOW
    )

    local, _ = _run(run_source(_LocalAdapter(["local-1"], body_bytes=50_000), NullResolver()))

    assert local.status == RunStatus.SUCCESS, local.error


def test_runs_recorded_before_provider_evidence_still_set_the_soft_block_basis(
    synthetic_site: SourceSite,
) -> None:
    # Deployed history predates detail_json["provider"]; the local-only filter
    # must read an absent key as local, or every existing site would lose its
    # EC-007 basis and stop catching soft-blocked pages.
    _seed_full_runs(synthetic_site, body_bytes=50_000, provider_kind=None, count=3)

    run, _ = _run(run_source(_LocalAdapter(["local-1"], body_bytes=100), NullResolver()))

    assert run.status == RunStatus.FAILED
    assert run.failure_class == RunFailureClass.ANTI_BOT


