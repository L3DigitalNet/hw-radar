"""MS2-D-14 Actor contract: drift guards, input validation, and the run classifier.

The fixtures under tests/fixtures/apify_contract/v1/ are generated by the Actor's
own test harness (actors/hw-radar-synthetic-collector/tests/support.py) from its
faultMode, and the Actor's tests fail if they drift, so the classifier is tested
against what the real Actor emits rather than hand-written JSON. This file never
imports the Actor; it reads the committed schema files only.
"""

