def test_rejected_rows_make_the_run_a_partial_failure(synthetic_site: SourceSite) -> None:
    # A dropped row is not usable, so a run that dropped one cannot be complete
    # and cannot delist: the listing behind that row would otherwise be marked
    # absent by the very sweep that saw it.
    fixture = _fixture("complete")
    rows = copy.deepcopy(fixture["datasetItems"])
    rows[0]["siteKey"] = "another-site"
    provider = _provider(_provider_run(synthetic_site, fixture), FakeApify(rows, fixture["output"]))

    batch, parsed = _fetch_and_parse(provider)
    scope = provider.delist_scope(batch, parsed)
    evidence = provider.run_evidence(batch, parsed, scope, run_kind=RunKind.FULL)

    assert len(batch.items) == len(rows)
    assert len(parsed) == len(rows) - 1
    assert evidence.completeness is RunCompleteness.PARTIAL_FAILURE
    assert scope is None


