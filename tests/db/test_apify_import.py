def _provider_run(
    site: SourceSite, fixture: dict[str, Any], *, run_kind: RunKind = RunKind.FULL
) -> ProviderRun:
    admitted = fixture["admitted"]["queryScope"]
    now = timezone.now()
    return ProviderRun.objects.create(
        source_site=site,
        external_run_id=f"run-{fixture['fixture']}",
        import_idempotency_key=f"apify:run-{fixture['fixture']}",
        actor_ref=ACTOR,
        contract_schema_version="hw-radar-run/v1",
        query_scope=admitted,
        scope_key=admitted["collectionScope"],
        memory_mb=256,
        timeout_s=120,
        max_items=admitted["maxItems"],
        max_pages=admitted["maxPages"],
        admission_class=AdmissionClass.WATCH_REFRESH,
        run_kind=run_kind,
        admitted_at=now - timedelta(minutes=10),
        remote_status=fixture["remoteStatus"],
        started_at=datetime.fromisoformat(fixture["startedAt"]),
        dataset_id=DATASET,
        kv_store_id=KV_STORE,
        storage_cleanup_due_at=now + timedelta(hours=24),
    )


def _provider(row: ProviderRun, fake: FakeApify, *, actor_name: str = ACTOR) -> ApifyImportProvider:
    client = ApifyClient(TOKEN, transport=httpx.MockTransport(fake))
    return ApifyImportProvider(row, client=client, actor_name=actor_name)


def _fake(fixture: dict[str, Any]) -> FakeApify:
    return FakeApify(list(fixture["datasetItems"]), fixture["output"])


def _import(provider: ApifyImportProvider) -> tuple[ScraperRun, RunStatus]:
    retention = provider.retention
    run, _ = _run(
        run_collection(
            provider,
            NullResolver(),
            retention_class=retention.retention_class,
            expires_policy=retention.expires_policy,
        )
    )
    return run, RunStatus(run.status)


def _evidence_json(run: ScraperRun) -> dict[str, object]:
    return cast(dict[str, object], run.detail_json["provider"])


def _fetch_and_parse(provider: ApifyImportProvider) -> tuple[RawBatch, list[ParsedListing]]:
    batch = _run(provider.fetch())
    return batch, provider.parse(batch)


